export const getQuotesByCharacter = (character) => {
  if (!character || character === 'all') return quotes
  return quotes.filter(q => q.character.toLowerCase().includes(character.toLowerCase()))
}

export const getQuotesByTheme = (theme) => {
  if (!theme || theme === 'all') return quotes
  return quotes.filter(q => q.theme === theme)
}

export const getQuotesByBook = (book) => {
  if (!book || book === 'all') return quotes
  return quotes.filter(q => q.book === book)
}

export const getRandomQuote = () => {
  const randomIndex = Math.floor(Math.random() * quotes.length)
  return quotes[randomIndex]
}

