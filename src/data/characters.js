export const getCharactersByRole = (role) => {
  const roleMap = {
    friends: ['Best Friend', 'Wife', 'D.A. Leader', 'Magizoologist', 'The Chosen One', 'Auror', 'Head of Auror Office'],
    mentors: ['Headmaster', 'Professor', 'Order Member', 'Auror'],
    family: ['Auror', 'Guardian', 'Cousin'],
    enemies: ['Dark Wizard', 'Death Eater', 'Snatcher', 'Ministry Official'],
    other: ['House-elf', 'Pranksters', 'Champion', 'Auror']
  }
  const roles = roleMap[role] || []
  return characters.filter(c => roles.some(r => c.role.includes(r)))
}

export const getCharactersByHouse = (house) => {
  if (house === 'all' || !house) return characters
  return characters.filter(c => c.house === house)
}

export const getCharacterById = (id) => characters.find(c => c.id === id)

export const searchCharacters = (query) => {
  const q = query.toLowerCase()
  return characters.filter(c =>
    c.name.toLowerCase().includes(q) ||
    c.alias.toLowerCase().includes(q) ||
    c.house.toLowerCase().includes(q) ||
    c.role.toLowerCase().includes(q)
  )
}

